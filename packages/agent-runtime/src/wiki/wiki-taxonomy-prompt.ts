/**
 * 分类提示词唯一真源 — 口诀 + 易混 + 分类树渲染
 *
 * classifier（归档分类）/ reclassifier（重编目）/ 全库编目共用这一份。
 * 此前两处各自硬编码同一段口诀，长期漂移成「classify 6 条易混、reclassify 只有 3 条」，
 * 换分类体系时要改两处且容易漏——故收拢到本模块。
 *
 * 设计：docs/design/记忆设计/2026-08-31-wiki-intelligent-vault-design.md v1.1 §4
 */

import type { WikiTopicTree } from "./wiki-topic-tree.js";

/**
 * 渲染当前主题树为「可选目录」列表。
 * 模型永远只能从当前树里选节点，故这段必须动态生成，不能写死。
 */
export function buildTopicTreeLines(tree: WikiTopicTree): string {
  return tree.categories.map((c) => `- ${c.name}：${c.subtopics.join("、")}`).join("\n");
}

/**
 * 完整分类指引：角色 + 口诀 + 易混 + 可选目录 + 规则。
 *
 * 口诀正文按 v2 树的四个大类边界写死（与树同名同步维护，单测断言口诀覆盖树中全部大类）；
 * 「可选目录」段动态渲染当前树，用户自建大类也会出现在里面。
 */
export function buildTaxonomyGuide(tree: WikiTopicTree): string {
  return [
    "你是个人资料归档助手。按「这份资料和我的哪个生活域有关」分类，不要按学科领域分类。",
    "",
    "## 口诀",
    "- 跟上班、项目、赚钱有关 → 工作",
    "- 主动在学、在读、在备考 → 学习",
    "- 私人、家庭、证件、账单、日记 → 生活",
    "- 网上看到先留着、可套用的模板素材 → 收藏",
    "- 拿不准 → 不分类（留收件箱）",
    "",
    "## 易混",
    "- 为了完成工作任务用的资料 → 工作；为了个人提升在学的 → 学习（同一学科内容可进不同大类）",
    "- 个人证件/票据/保险/履历 → 生活；跟工作签约的合同、给客户的材料 → 工作",
    "- 空白可套用的模板、范例、素材 → 收藏，即使内容关于工作",
    "- 网页链接默认 → 收藏，除非明显属于某个具体工作项目",
    "",
    "## 可选目录（只能从这里选，禁止自造名称）",
    buildTopicTreeLines(tree),
    "",
    "## 规则",
    "- **大类必填，小类可以留空**：能确定大类但拿不准小类时，只给 category，subtopic 留空——这是正常结果，不要为了填满而硬猜",
    "- 大类都拿不准时 category、subtopic 都留空，skip=true，reason 说明",
    "- 只能使用上方列出的名称，不要发明新名称或使用「其他」「未分类」等占位词",
    "- 综合文件名、所在文件夹路径、内容摘要判断；**文件夹路径往往已经表达了用户的意图，优先采信**",
    "- 临时存放仅用户可写，AI 不得选用",
  ].join("\n");
}
